#!/usr/bin/env bash
# Build the Sahara APK from the pinned upstream: fetch, apply overlay and patches, configure, assemble.
#
# Usage: [SAHARA_ABI=arm64-v8a|x86_64] scripts/build.sh [debug|release]       (default: arm64-v8a, debug)
#   arm64-v8a is the phone build. x86_64 exists only so CI can run the app on an x86 Android emulator;
#   Mozilla publishes a GeckoView for each ABI under the same build ID.
#
# Prerequisite, once per machine: scripts/bootstrap-android.sh (needs scripts/fetch-upstream.sh first;
# this script runs the fetch itself and skips it when the tree is already extracted).
# Behind a TLS-intercepting proxy (the cloud sandbox) run `. scripts/proxy-env.sh` first.
#
# Output: the arm64 APK, path printed at the end. A release build is UNSIGNED; see scripts/sign-apk.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../upstream/PIN
source "${SAHARA_PIN_FILE:-$ROOT/upstream/PIN}"
BUILD_DIR="${SAHARA_BUILD_DIR:-$ROOT/build}"
TREE="$BUILD_DIR/upstream"
MOZBUILD="${MOZBUILD_STATE_PATH:-$HOME/.mozbuild}"

die() { echo "build: $*" >&2; exit 1; }

abi="${SAHARA_ABI:-arm64-v8a}"
case "$abi" in
  arm64-v8a) target="aarch64-linux-android" ;;
  x86_64) target="x86_64-linux-android" ;;
  *) die "unsupported SAHARA_ABI: $abi (use arm64-v8a or x86_64)" ;;
esac

variant="${1:-debug}"
case "$variant" in
  debug) task="fenix:assembleDebug"; apk_glob="fenix-$abi-debug.apk"; extra_args=() ;;
  # Upstream signs release builds with the public Android debug key unless told not to. We want them
  # unsigned so that scripts/sign-apk.sh is the only thing that signs, with our own key.
  release) task="fenix:assembleRelease"; apk_glob="fenix-$abi-release-unsigned.apk"; extra_args=(-PdisableDebugSigning) ;;
  *) die "unknown variant: $variant (use debug or release)" ;;
esac

[[ -x "$MOZBUILD/nimbus-fml/nimbus-fml" ]] || die "nimbus-fml missing; run scripts/bootstrap-android.sh first"
[[ -d "$MOZBUILD/android-sdk-linux/platforms" ]] || die "Android SDK missing; run scripts/bootstrap-android.sh first"

echo "== upstream"
"$ROOT/scripts/fetch-upstream.sh"
if [[ ! -f "$TREE/.sahara-applied" ]]; then
  "$ROOT/scripts/apply-overlay.sh"
else
  echo "overlay and patches already applied (use scripts/apply-overlay.sh --reapply to redo)"
fi

echo "== configure"
sed "s|@TARGET@|$target|" "$ROOT/build-config/mozconfig" > "$TREE/mozconfig"
export MOZ_BUILD_DATE="$SAHARA_GECKOVIEW_BUILDID"      # selects Mozilla's published GeckoView build
export NIMBUS_FML="$MOZBUILD/nimbus-fml/nimbus-fml"
(cd "$TREE" && ./mach configure)
OBJDIR="$TREE/objdir-sahara"

echo "== generated sources"
# A full Gecko build writes these; Gradle does not. buildid.h must match the GeckoView build ID.
printf '#define MOZ_BUILDID %s\n' "$MOZ_BUILD_DATE" > "$OBJDIR/buildid.h"
# Kotlin/Java sources and WebCompat add-on files generated by Python scripts.
make_bin="$(command -v gmake || command -v make)" || die "GNU make not found"
(cd "$OBJDIR" && "$make_bin" mobile/android/pre-export >/dev/null)

echo "== gradle $task"
# Memory: the tree gives the Gradle JVM a 7 GB heap, and by default the Kotlin compiler runs in a second
# JVM with another 7 GB, which is enough to get the build OOM-killed on a 16 GB machine. Compiling Kotlin
# inside the Gradle JVM keeps one big heap instead of two. The daemon is stopped afterwards so a finished
# build does not keep gigabytes pinned (set SAHARA_KEEP_DAEMON=1 to keep it for fast local rebuilds).
if [[ -z "${SAHARA_KEEP_DAEMON:-}" ]]; then
  trap '(cd "$TREE" && ./mach gradle --stop >/dev/null 2>&1) || true' EXIT
fi
(cd "$TREE" && ./mach gradle "$task" -Pkotlin.compiler.execution.strategy=in-process "${extra_args[@]}")

apk="$(find "$OBJDIR/gradle/build/mobile/android/fenix/app/outputs/apk" -name "$apk_glob" | head -n 1)"
[[ -n "$apk" ]] || die "build finished but $apk_glob was not found"
echo "APK: $apk"
